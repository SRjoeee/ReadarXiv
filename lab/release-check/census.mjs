// ---------------------------------------------------------------- taking a tree

const ids = (scan, paths) => paths.filter(p => scan.files.has(p)).map(p => `${scan.repo}:${p}`)
const exportsOfPackages = (scan, dir) =>
  [...scan.files.keys()]
    .filter(f => f.startsWith(`${dir}/`) && /^[^/]+\/package\.json$/.test(f.slice(dir.length + 1)))
    .flatMap(m => {
      const json = JSON.parse(readFileSync(join(scan.root, m), 'utf8'))
      const ex = typeof json.exports === 'string' ? [json.exports] : Object.values(json.exports ?? {}).map(v => (typeof v === 'object' ? (v.import ?? v.default) : v))
      return ex.filter(Boolean).map(e => join(dirname(m), e).split('\\').join('/'))
    })
/** a build's entry files of one arm ('entries', 'today', 'v2') */
function entriesOf(scan, spec) {
  if (!spec) return []
  if (Array.isArray(spec)) return ids(scan, spec)
  if (spec.under) return ids(scan, [...scan.files.keys()].filter(f => f.startsWith(spec.under) && ['code', 'html'].includes(scan.files.get(f).kind)))
  if (spec.packageExports) return ids(scan, exportsOfPackages(scan, spec.packageExports))
  return []
}
/** the roots of every build: all of them now, and those the cut-over keeps; its seeds and their switch modules */
export function rootsOf(scans) {
  const now = []
  const after = []
  const seeds = []
  const switches = []
  const builds = []
  for (const s of scans)
    for (const b of s.profile.builds ?? []) {
      const shared = entriesOf(s, b.entries)
      const old = entriesOf(s, b.today)
      const kept = entriesOf(s, b.v2)
      now.push(...shared, ...old, ...kept)
      after.push(...shared, ...kept)
      builds.push({ repo: s.repo, name: b.name, now: [...shared, ...old, ...kept], after: [...shared, ...kept], old, why: b.cut?.why ?? b.why ?? null })
      if (b.cut) {
        // (a seed ending in / is every file under it)
        const named = b.cut.seeds.flatMap(x => (x.endsWith('/') ? [...s.files.keys()].filter(f => f.startsWith(x) && s.files.get(f).role === 'product') : [x]))
        seeds.push(...ids(s, named).map(id => ({ id, why: b.cut.why, build: b.name })))
        switches.push(...ids(s, [b.cut.switch].flat()))
      }
    }
  return { now, after, seeds, switches, builds }
}
const publicEntriesOf = scan => {
  const p = scan.profile.publicEntries
  if (!p) return new Set()
  return new Set([...(p.packageExports ? exportsOfPackages(scan, p.packageExports) : []), ...(p.files ?? [])].filter(f => scan.files.has(f)))
}

/** a view of the trees: every file, or the files `alive` holds */
function viewOf(label, scans, graph, alive = null) {
  const files = []
  for (const s of scans) for (const [path, f] of s.files) if (!alive || alive.has(`${s.repo}:${path}`)) files.push({ id: `${s.repo}:${path}`, repo: s.repo, path, f, scan: s })
  return { label, scans, graph, alive, files, byId: new Map(files.map(x => [x.id, x])) }
}

/** what the cut-over deletes, by the graph (DEFINITIONS.cutover) */
export function cutoverOf(scans, graph) {
  const r = rootsOf(scans)
  const cut = new Set(r.seeds.map(s => s.id))
  const reachNow = reach(graph, r.now)
  const reachAfter = reach(graph, r.after, cut)
  const fileOf = id => {
    const [repo, ...p] = id.split(':')
    return scans.find(s => s.repo === repo)?.files.get(p.join(':'))
  }
  const deleted = new Set([...reachNow.keys()].filter(id => !reachAfter.has(id) && fileOf(id)?.role === 'product'))
  // (a JavaScript module's hand-written declaration goes with it)
  for (const id of [...deleted]) {
    const d = id.replace(/\.(m|c)?js$/, (_, m) => `.d.${m ?? ''}ts`)
    if (d !== id && fileOf(d)) deleted.add(d)
  }
  // (a seed some module the cut-over keeps still imports, other than the switch that chooses it: the old arm the new one needs)
  const kept = r.seeds.flatMap(s => (graph.into.get(s.id) ?? []).filter(e => reachAfter.has(e.from) && !r.switches.includes(e.from)).map(e => ({ seed: s.id, by: e.from, line: e.line, type: e.type })))
  const goWith = new Set()
  for (const s of scans)
    for (const [path, f] of s.files) {
      if (f.role === 'product' || f.role === 'config' || f.role === 'docs') continue
      const id = `${s.repo}:${path}`
      if ((graph.out.get(id) ?? []).some(e => deleted.has(e.to))) goWith.add(id)
    }
  return { roots: r, deleted, goWith, kept, reachNow, reachAfter, partial: scans.length < 2 }
}

