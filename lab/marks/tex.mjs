import { readFileSync, writeFileSync } from 'node:fs'

const E = new URL('../../src/pdf-reader/engine/', import.meta.url)
const OUT = new URL('../../packages/engine/src/marks/tex.ts', import.meta.url)
const im = p => import(new URL(p, E).href)
const text = p => readFileSync(new URL(p, E), 'utf8')
const M = await im('layout/marks.mjs')
const F = await im('source/latex-front.mjs')
const T = await im('pipeline/typeset/tex.mjs')
