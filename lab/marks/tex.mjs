/** the regular expression literal `const NAME = /…/flags` (or `, NAME = /…/` on a line of two) in a module's text */
function regexOf(src, name) {
  const m = new RegExp(`(?:const|,) ${name} = /`).exec(src)
  if (!m) throw new Error(`no regular expression ${name}`)
  let i = m.index + m[0].length
  const start = i
  let inClass = false
  for (; i < src.length; i++) {
    const c = src[i]
    if (c === '\\') { i++; continue }
    if (c === '[') inClass = true
    else if (c === ']') inClass = false
    else if (c === '/' && !inClass) break
  }
  const flags = /^[a-z]*/.exec(src.slice(i + 1))[0]
  return new RegExp(src.slice(start, i), flags)
}
/** the value of `const NAME = <literal>` (an array, object or `new Set([...])`), names in `scope` bound */
function literal(src, name, scope = {}) {
  const at = src.indexOf(`const ${name} = `)
  if (at < 0) throw new Error(`no ${name}`)
  let i = at + `const ${name} = `.length
  const start = i
  let depth = 0
  for (; i < src.length; i++) {
    const c = src[i]
    if (c === "'" || c === '"' || c === '`') { for (i++; src[i] !== c; i++) if (src[i] === '\\') i++; continue }
    if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); continue }
    if ('{[('.includes(c)) depth++
    else if ('}])'.includes(c) && --depth === 0) break
  }
  const value = new Function(...Object.keys(scope), `return ${src.slice(start, i + 1)}`)(...Object.values(scope))
  return value instanceof Set ? [...value] : value
}

const marks = text('layout/marks.mjs')
const front = text('source/latex-front.mjs')
const live = text('pipeline/live.mjs')
const roles = text('rules/arg-roles.mjs')
const PATTERNS = ['STRUCTURE', 'MATH', 'CITE', 'EQREF', 'REF', 'CODE', 'URL', 'NUMBER', 'FOOTNOTE_MARK', 'INLINE', 'WORD_END', 'ENDS_ENV', 'ENDS_IN_CS', 'VERBATIM_ARG', 'BREAK', 'BOXY', 'COLOUR_OPEN', 'COLOUR_SWITCH']
const patterns = Object.fromEntries(PATTERNS.map(n => [n, regexOf(marks, n)]))
// (patch's own INLINE is kept equal to marks.mjs's: latex-front.mjs; held here too)
if (regexOf(front, 'INLINE').source !== patterns.INLINE.source) throw new Error("latex-front.mjs INLINE is not marks.mjs's")
const DRAFT = `${literal(live, 'DRAFT', { DRAFT_OPTION: L.DRAFT_OPTION }).join('\n')}\n`
const NAMES_OFF = /const NAMES_OFF = '([^']*)'/.exec(live)?.[1]?.replace(/\\\\/g, '\\')
if (!NAMES_OFF) throw new Error('no NAMES_OFF')
const REGIONS = M.regionsTex(['\u0000'], [])
const REGIONS_TAIL = '\\fi\\makeatother'
if (!REGIONS.endsWith(REGIONS_TAIL)) throw new Error('regionsTex: its frame changed')
const SYMBOL = `@(?![A-Za-z@])|[${K.INK_FREE_SYMBOLS.map(s => s[1]).filter(c => c !== '@' && c !== ' ').map(c => `\\${c}`).join('')}\\s]`
const WORD = `(?:${K.INK_FREE_WORDS.join('|')})(?![A-Za-z@])`
const INK_FREE = String.raw`^\s*\\(?:${SYMBOL}|${WORD})(?:\{\})?\s*$`
if (!new RegExp(INK_FREE).test('\\relax') || K.inkFree('\\relax{}') !== new RegExp(INK_FREE).test('\\relax{}')) throw new Error('inkFree changed')
const PREFIX = String.raw`^\s*\\(?:${K.PREFIX_WORDS.join('|')})\s*$`
const TEXTLESS = literal(roles, 'TEXTLESS', { BREAK_HINTS: K.BREAK_HINTS })

const j = v => JSON.stringify(v)
const re = r => `/${r.source}/${r.flags}`
const out = `// Generated by lab/marks/tex.mjs from src/pdf-reader/engine (latex-front.mjs, layout/marks.mjs, pipeline/live.mjs,
// pipeline/typeset/tex.mjs, rules/tex-kernel.mjs, rules/arg-roles.mjs, layout/names.mjs). Do not edit: run the script again.
// The TeX the marked original's head holds, and the placement's name classes as today's marks writer has them.

/** the unit marks (\\axtmark, \\axtend, columns), latex-front.mjs MARK_DEF; the DVI drivers' (latex: \\pdfoutput=0) */
export const MARK_DEF = ${j(F.MARK_DEF)}
export const DVI_MARK_DEF = ${j(F.DVI_MARK_DEF)}
/** the layout marks (points, placeholders' marks, babel names, the gate, backref, colours), marks.mjs LAYOUT_TEX */
export const LAYOUT_TEX = ${j(M.LAYOUT_TEX)}
export const DVI_LAYOUT_TEX = ${j(M.DVI_LAYOUT_TEX)}
/** the document's end (AXT-END) and each unit's lines (\\axtlines, AXT-LINES), typeset/tex.mjs */
export const END_TEX = ${j(T.END_TEX)}
export const LINES_TEX = ${j(T.LINES_TEX)}
/** graphicx's draft with each frame's corners marked; the final pass's line in its first line's place (live.mjs) */
export const DRAFT = ${j(DRAFT)}
export const DRAFT_OPTION = ${j(L.DRAFT_OPTION)}
export const NO_DRIVER_GROUP = ${j(L.NO_DRIVER_GROUP)}
/** the babel names' marks off (live.mjs NAMES_OFF) */
export const NAMES_OFF = ${j(NAMES_OFF)}
/** the code regions' points (marks.mjs regionsTex): its frame, each code environment's hook between */
export const REGIONS_HEAD = ${j(REGIONS.slice(0, -REGIONS_TAIL.length))}
export const REGIONS_TAIL = ${j(REGIONS_TAIL)}
/** a placeholder whose rendering is never ink (marks.mjs INVISIBLE) */
export const INVISIBLE = ${re(M.INVISIBLE)}
${PATTERNS.map(n => `export const ${n} = ${re(patterns[n])}`).join('\n')}
/** a whole source that is one of TeX's own that set no ink (tex-kernel.mjs inkFree), or LaTeX's prefix (prefixWord) */
export const INK_FREE = new RegExp(${j(INK_FREE)})
export const PREFIX = new RegExp(${j(PREFIX)})
/** the commands that set no letters, their arguments all there (arg-roles.mjs TEXTLESS) */
export const TEXTLESS: ReadonlySet<string> = new Set(${j(TEXTLESS)})
/** babel's names by key and their English words (layout/names.mjs) */
export const NAME_KEYS: readonly string[] = ${j(N.NAME_KEYS)}
export const NAME_ENGLISH: Readonly<Record<string, string>> = ${j(N.NAME_ENGLISH)}
/** the list backref sets after an entry, the reader's element for it (latex-front.mjs BACKREF_LIST) */
export const BACKREF_LIST = ${j(F.BACKREF_LIST)}
`
const formatted = execFileSync('pnpm', ['exec', 'biome', 'format', '--stdin-file-path=packages/engine/src/marks/tex.ts'], {
  input: out,
  cwd: new URL('../..', import.meta.url).pathname,
  maxBuffer: 1 << 26,
}).toString()
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== formatted) {
    console.error('marks/tex.ts differs from its sources: run node --experimental-strip-types lab/marks/tex.mjs')
    process.exit(1)
  }
} else writeFileSync(OUT, formatted)
console.log(`marks/tex.ts: ${formatted.length} characters`)
