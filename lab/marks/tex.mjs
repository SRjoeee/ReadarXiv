// lab/marks/tex.mjs: writes packages/engine/src/marks/tex.ts, the placement's two classes of an element that sets no ink of
// its own (src/pdf-reader/engine/layout/marks.mjs INVISIBLE, STRUCTURE) as the package's run-in labels read them
// (marks/run-ins.ts inkless). The package holds a copy because it imports nothing of the extension's src/
// (packages/README.md); this keeps the copy today's.
//   node --experimental-strip-types lab/marks/tex.mjs [--check]
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

const E = new URL('../../src/pdf-reader/engine/', import.meta.url)
const OUT = new URL('../../packages/engine/src/marks/tex.ts', import.meta.url)
const M = await import(new URL('../../../packages/engine/src/marks/marks.mjs', E).href)
const marks = readFileSync(new URL('../../../packages/engine/src/marks/marks.mjs', E), 'utf8')

/** the regular expression literal `const NAME = /…/flags` (or `, NAME = /…/` on a line of two) in a module's text */
function regexOf(src, name) {
  const m = new RegExp(`(?:const|,) ${name} = /`).exec(src)
  if (!m) throw new Error(`no regular expression ${name}`)
  let i = m.index + m[0].length
  const start = i
  let inClass = false
  for (; i < src.length; i++) {
    const c = src[i]
    if (c === '\\') { i++; continue }
    if (c === '[') inClass = true
    else if (c === ']') inClass = false
    else if (c === '/' && !inClass) break
  }
  const flags = /^[a-z]*/.exec(src.slice(i + 1))[0]
  return new RegExp(src.slice(start, i), flags)
}

const re = r => `/${r.source}/${r.flags}`
const out = `// Generated by lab/marks/tex.mjs from src/pdf-reader/engine/layout/marks.mjs. Do not edit: run the script again.
// The placement's classes of an element that sets no ink of its own, as today's marks writer has them.

/** a placeholder whose rendering is never ink (marks.mjs INVISIBLE) */
export const INVISIBLE = ${re(M.INVISIBLE)}
/** a character the scanner keeps as structure, with no ink of its own (marks.mjs STRUCTURE) */
export const STRUCTURE = ${re(regexOf(marks, 'STRUCTURE'))}
`
const formatted = execFileSync('pnpm', ['exec', 'biome', 'format', '--stdin-file-path=packages/engine/src/marks/tex.ts'], {
  input: out,
  cwd: new URL('../..', import.meta.url).pathname,
  maxBuffer: 1 << 26,
}).toString()
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== formatted) {
    console.error('marks/tex.ts differs from its sources: run node --experimental-strip-types lab/marks/tex.mjs')
    process.exit(1)
  }
} else writeFileSync(OUT, formatted)
console.log(`marks/tex.ts: ${formatted.length} characters`)
