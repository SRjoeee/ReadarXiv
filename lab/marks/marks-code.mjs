// lab/marks/marks-code.mjs [--check]: writes packages/engine/src/compile/marks-code.ts, the digest of the code that decides
// the marked tree (the source reader, the marks writer and its TeX), which the instrument's cache keys on
// (packages/engine/src/compile/cache.ts). --check: exits 1 where the file holds another digest than the code's. Not shipped.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { join } from 'node:path'

const ROOT = new URL('../../', import.meta.url).pathname
const SRC = 'packages/engine/src/'
/** the code a marked tree is a function of: every file of the source reader, the marks writer, its classes and its TeX */
export const MARKS_FILES = [
  ...readdirSync(join(ROOT, SRC, 'source')).filter(f => f.endsWith('.ts')).map(f => `${SRC}source/${f}`),
  `${SRC}marks/mark.ts`,
  `${SRC}marks/classes.ts`,
  `${SRC}marks/tex.ts`,
  `${SRC}marks/statements.ts`,
  `${SRC}compile/recover.ts`,
].sort()
export function marksCode() {
  const h = createHash('sha256')
  for (const f of MARKS_FILES) h.update(f).update('\0').update(readFileSync(join(ROOT, f))).update('\0')
  return h.digest('hex')
}
const OUT = join(ROOT, SRC, 'compile/marks-code.ts')
const names = MARKS_FILES.map(f => f.slice(SRC.length)).join(', ').replace(/(.{1,110})(?:, |$)/g, '//   $1\n')
const text = `// Generated by lab/marks/marks-code.mjs (\`--check\` holds it): the digest of the code that decides the marked tree, which the
// instrument's cache keys on (cache.ts). Do not edit: run the script again after a change to any of these files:
${names}export const MARKS_CODE = '${marksCode()}'
`
if (process.argv[1] === new URL(import.meta.url).pathname) {
  if (process.argv.includes('--check')) {
    const had = readFileSync(OUT, 'utf8')
    if (had !== text) {
      console.error('marks-code.ts is not the code\'s digest: node lab/marks/marks-code.mjs')
      process.exit(1)
    }
  } else writeFileSync(OUT, text)
}
