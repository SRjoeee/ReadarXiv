// lab/source/tables.mjs: writes packages/engine/src/source/tables.ts, the kernel's text symbols (src/pdf-reader/engine/rules/
// text-symbols.mjs) as the package's locate reads them (a text symbol's character: locate.ts symbolText). The package holds
// a copy because it imports nothing of the extension's src/ (packages/README.md); this keeps the copy today's.
//   node lab/source/tables.mjs [--check]
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

const RULES = new URL('../../src/pdf-reader/engine/rules/', import.meta.url)
const OUT = new URL('../../packages/engine/src/source/tables.ts', import.meta.url)
const { TEXT_SYMBOLS } = await import(new URL('text-symbols.mjs', RULES).href)

const j = v => JSON.stringify(v)
const out = `// Generated by lab/source/tables.mjs from src/pdf-reader/engine/rules/text-symbols.mjs. Do not edit: run the script again.
/** a LaTeX text symbol's character (\\S, \\%: the kernel's text symbols, rules/text-symbols.mjs TEXT_SYMBOLS) */
export const TEXT_SYMBOLS: Readonly<Record<string, string>> = ${j(TEXT_SYMBOLS)}
`
// (as the package's formatter writes it: Biome formats packages/**)
const formatted = execFileSync('pnpm', ['exec', 'biome', 'format', '--stdin-file-path=packages/engine/src/source/tables.ts'], {
  input: out,
  cwd: new URL('../..', import.meta.url).pathname,
  maxBuffer: 1 << 26,
}).toString()
if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== formatted) {
    console.error('tables.ts differs from its sources: run node lab/source/tables.mjs')
    process.exit(1)
  }
} else writeFileSync(OUT, formatted)
console.log(`tables.ts: ${formatted.length} characters`)
