// Writes src/config/language-names.ts: the target languages' names in Traditional Chinese, Japanese and Korean, read from
// CLDR through the running Node's Intl.DisplayNames (UI.md §6: a target's name in the interface's language). Run it once
// with `pnpm tsx scripts/language-names.ts` and review the diff: the names are data, the file records which CLDR they
// came from, and a different Node may carry a different CLDR, so nothing regenerates or checks it on its own.
import { writeFileSync } from 'node:fs'
import { LANG_CODES, type LangCode, toBcp47 } from '../src/config/languages'

const OUT = 'src/config/language-names.ts'

/**
 * The tag CLDR is asked for, where the one sent to a translator would lose what the row has to say: Chinese by its
 * script (`zh` alone is "Chinese", `zh-TW` "Chinese (Taiwan)"), and the four entries the English interface names by
 * their script too (LANG_CODE_TO_EN_UI_NAME: "Bosnian (Cyrillic)"; the reader gets that script from the LLM)
 */
const ASK: Partial<Record<LangCode, string>> = { cmn: 'zh-Hans', 'cmn-Hant': 'zh-Hant', bos: 'bs-Cyrl', srp: 'sr-Cyrl', uzn: 'uz-Cyrl', azj: 'az-Cyrl' }

/** Each language's own parentheses: Japanese sets full-width ones with no space, Korean half-width ones with no space */
const TIDY: Record<string, (name: string) => string> = {
  'zh-TW': name => name,
  ja: name => name.replace(/\s*\(([^)]*)\)/g, '\uff08$1\uff09'),
  ko: name => name.replace(/\s+\(/g, '('),
}

const TABLES = { 'zh-TW': 'LANG_CODE_TO_ZH_TW_NAME', ja: 'LANG_CODE_TO_JA_NAME', ko: 'LANG_CODE_TO_KO_NAME' } as const

const blocks: string[] = []
const missing: string[] = []
for (const [locale, table] of Object.entries(TABLES)) {
  const names = new Intl.DisplayNames(locale, { type: 'language', fallback: 'none' })
  const rows: string[] = []
  for (const code of LANG_CODES) {
    let name: string | undefined
    try { name = names.of(ASK[code] ?? toBcp47(code)) } catch { name = undefined }
    if (!name) { missing.push(`${locale} ${code}`); continue }
    rows.push(`  ${JSON.stringify(code)}: ${JSON.stringify(TIDY[locale]!(name))},`)
  }
  blocks.push(`export const ${table}: Partial<Record<LangCode, string>> = {\n${rows.join('\n')}\n}\n`)
}

const { icu, cldr } = process.versions as Record<string, string>
const header = `// Generated by scripts/language-names.ts from CLDR ${cldr} (ICU ${icu}, Node ${process.version}): edit the script and run it,
// not this file. The target languages' names in Traditional Chinese, Japanese and Korean, for the popup's and the settings
// page's language rows and menus (UI.md §6). CLDR's data is under the Unicode License v3 (docs/THIRD_PARTY.md).
// A language CLDR does not name in one of them is left out, and that interface reads its English name (UI.md §6).
// Data alone, importing no module: the website bundles the pin's interface strings without config/languages (a seam).
import type { LangCode } from './languages'
`
writeFileSync(OUT, `${header}\n${blocks.join('\n')}`)
console.log(`wrote ${OUT}; not named by CLDR: ${missing.join(', ') || 'none'}`)
